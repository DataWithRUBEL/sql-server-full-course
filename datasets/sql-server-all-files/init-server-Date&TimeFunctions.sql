/* ============================================================
   SCHEMA
   ============================================================ */

CREATE SCHEMA Sales;
GO


/* ============================================================
   ORDERS TABLE
   Realistic E-Commerce Sales Data
   ============================================================ */

CREATE TABLE Sales.Orders
(
    OrderID       INT PRIMARY KEY,
    CustomerID    INT,
    EmployeeID    INT,
    OrderDate     DATE,
    CreationTime  DATETIME2(0),
    ShipDate      DATE,
    OrderAmount   DECIMAL(12,2)
);
GO


/* ============================================================
   EMPLOYEES TABLE
   ============================================================ */

CREATE TABLE Sales.Employees
(
    EmployeeID INT PRIMARY KEY,
    EmployeeName VARCHAR(100),
    BirthDate DATE,
    HireDate DATE
);
GO



