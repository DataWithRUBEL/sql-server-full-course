/* =============================================================================
   SALES SCHEMA
   ---------------------------------------------------------------------------
   Sales-related tables এখানে রাখা হবে।
============================================================================= */

CREATE SCHEMA Sales;
GO




/* =============================================================================
   TABLE: Sales.Orders

   বাস্তব e-commerce কোম্পানিতে customer যখন order করে,
   তখন order date/time সংরক্ষণ করা হয়।

   DATETIME2:
   - বেশি precision
   - নতুন application-এর জন্য preferred
============================================================================= */

CREATE TABLE Sales.Orders
(
    OrderID         INT PRIMARY KEY,
    CustomerID      INT NOT NULL,
    OrderDateTime   DATETIME2(7) NOT NULL,
    ShipDateTime    DATETIME2(7) NULL,
    DeliveryDateTime DATETIME2(7) NULL,
    OrderAmount     DECIMAL(12,2) NOT NULL
);
GO


